import { defineField, defineType } from 'sanity'
const row = (name: string, fields: string[]) => ({ type: 'object', name, fields: fields.map((f) => ({ name: f, type: 'string' })) })
export default defineType({
  name: 'homePage', title: 'Home page', type: 'document',
  groups: [{ name: 'hero', default: true }, { name: 'sections' }, { name: 'seo' }],
  fields: [
    defineField({ name: 'eyebrow', type: 'string', group: 'hero' }),
    defineField({ name: 'headline', type: 'string', group: 'hero' }),
    defineField({ name: 'subhead', type: 'text', rows: 2, group: 'hero' }),
    defineField({ name: 'heroNote', type: 'string', group: 'hero' }),
    defineField({ name: 'formTitle', type: 'string', group: 'hero' }),
    defineField({ name: 'compareHeading', type: 'string', group: 'sections' }),
    defineField({ name: 'compareRows', type: 'array', group: 'sections', of: [row('compareRow', ['label', 'ours', 'theirs'])] }),
    defineField({ name: 'storiesHeading', type: 'string', group: 'sections' }),
    defineField({ name: 'storiesIntro', type: 'string', group: 'sections' }),
    defineField({ name: 'testimonials', type: 'array', of: [{ type: 'reference', to: [{ type: 'testimonial' }] }], group: 'sections' }),
    defineField({ name: 'costHeading', type: 'string', group: 'sections' }),
    defineField({ name: 'costIntro', type: 'text', rows: 2, group: 'sections' }),
    defineField({ name: 'costRows', type: 'array', group: 'sections', of: [row('costRow', ['label', 'allOn4', 'threeOn6'])] }),
    defineField({ name: 'costFine', type: 'text', rows: 2, group: 'sections' }),
    defineField({ name: 'beforeAfterHeading', type: 'string', group: 'sections' }),
    defineField({ name: 'beforeAfterIntro', type: 'string', group: 'sections' }),
    defineField({ name: 'beforeAfters', type: 'array', of: [{ type: 'reference', to: [{ type: 'beforeAfter' }] }], group: 'sections' }),
    defineField({ name: 'steps', type: 'array', group: 'sections', of: [{ type: 'object', name: 'step', fields: [{ name: 'title', type: 'string' }, { name: 'text', type: 'text', rows: 2 }] }] }),
    defineField({ name: 'boneHeading', type: 'string', group: 'sections' }),
    defineField({ name: 'boneBody', type: 'text', rows: 3, group: 'sections' }),
    defineField({ name: 'guaranteeHeading', type: 'string', group: 'sections' }),
    defineField({ name: 'guaranteeLede', type: 'text', rows: 2, group: 'sections' }),
    defineField({ name: 'guaranteePoints', type: 'array', of: [{ type: 'string' }], group: 'sections' }),
    defineField({ name: 'guaranteeFine', type: 'text', rows: 2, group: 'sections' }),
    defineField({ name: 'seo', type: 'seo', group: 'seo' }),
  ],
  preview: { prepare: () => ({ title: 'Home page' }) },
})
